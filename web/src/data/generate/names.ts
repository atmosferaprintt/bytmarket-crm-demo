const NO_FEM = new Set<string>();

export function femaleSurname(s: string): string {
  if (NO_FEM.has(s)) return s;
  if (s.endsWith('ов') || s.endsWith('ёв') || s.endsWith('ев') || s.endsWith('ин') || s.endsWith('ын')) return s + 'а';
  if (s.endsWith('ий')) return s.slice(0, -2) + 'ая';
  return s;
}

