/* Единые пороги для всех разделов. Одно понятие — одно число, иначе цифры на разных экранах спорят.
   Импорт: import { NO_MOVEMENT_DAYS, isBelowMin } from '../../data/thresholds'; */

/** «Без движения»: нет продаж и отгрузок столько дней. Везде — 60. */
export const NO_MOVEMENT_DAYS = 60;

/** «Скоро истекает срок»: партия с годностью в ближайшие N дней. */
export const EXPIRY_SOON_DAYS = 30;

/** Просрочка оплаты считается срочной с этого дня. Меньше — «Важно», не «Срочно». */
export const URGENT_OVERDUE_DAYS = 3;

/** «Пропустил привычный заказ»: прошло больше, чем привычная частота × этот множитель. */
export const MISSED_ORDER_FACTOR = 1.5;

/** Предложение на закупку: запас сверх срока поставки, дней. Товар, которого хватит дольше срока поставки + запаса, не предлагаем. */
export const SUGGEST_SAFETY_DAYS = 7;

/** Сколько дней продаж смотреть для «продаётся в день». */
export const SALES_WINDOW_DAYS = 30;

/** «Ниже минимума» — всё, что меньше минимального остатка, включая ноль. «Нет в наличии» — отдельный признак внутри него.
    Остаток для сравнения — доступно по магазину и складу вместе (факт − резерв). */
export function isBelowMin(availableTotal: number, minStock: number): boolean {
  return minStock > 0 && availableTotal < minStock;
}
