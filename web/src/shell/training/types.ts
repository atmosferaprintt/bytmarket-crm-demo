/* Подсказки режима обучения. Каждая подсказка — к элементу на экране (лучше всего к [data-hint="…"]).
   Разделы описывают свои подсказки в web/src/sections/<раздел>/hints.ts, общие — в shell/training/shellHints.ts.

   Пример:
   { id: 'register.pay', path: '/register', roles: ['seller'], target: '[data-hint="register.pay"]',
     title: 'Оплата', text: 'F9 — оплатить наличными без сдачи. …' }
*/
import type { RoleKey } from '../../data/types';

export interface HintDef {
  /** уникальный ключ: «раздел.что» — по нему помним, что подсказку уже видели */
  id: string;
  /** экран: точный путь ('/register', '/sales/returns'), список путей или '*' — на любом экране (окна, карточки, шапка) */
  path: string | string[];
  /** только для этих сотрудников; не указано — для всех, кто видит элемент */
  roles?: RoleKey[];
  /** CSS-селектор элемента; первый видимый на экране. Лучше [data-hint="…"] */
  target: string;
  title: string;
  /** 1–3 коротких предложения: что это и как этим пользоваться. Без «демо», без капса */
  text: string;
  /** только на телефоне или только на компьютере */
  device?: 'phone' | 'desktop';
  /** общая подсказка (поиск по таблице, вкладки…) — показывается, только если у элемента нет своей */
  generic?: boolean;
}
